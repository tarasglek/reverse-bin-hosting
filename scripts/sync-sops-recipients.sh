#!/usr/bin/env sh
# Rewrites .sops.yaml so the apt signing key is encrypted to every SSH key
# the maintainers publish on GitHub plus the CI age key, then re-encrypts the
# key file. Rerun after adding or removing a key on GitHub.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
GITHUB_USERS=${SOPS_GITHUB_USERS:-tarasglek}
CI_RECIPIENT_FILE="$ROOT/packaging/apt/ci-age-recipient.txt"
SECRET="packaging/apt/signing-key.sops.json"
SOPS=${SOPS:-$(command -v sops || echo "$ROOT/build/sops")}

# Fail closed: a failed fetch must not re-encrypt to the CI key alone and
# lock maintainers out.
maintainers=""
for user in $GITHUB_USERS; do
  keys=$(curl -fsSL "https://github.com/$user.keys") || { echo "error: cannot fetch GitHub keys of $user" >&2; exit 1; }
  # age accepts only ed25519 and RSA SSH keys.
  user_keys=$(printf '%s\n' "$keys" | grep -E '^ssh-(ed25519|rsa) ' | cut -d' ' -f1,2) \
    || { echo "error: $user has no ed25519/RSA SSH key on GitHub" >&2; exit 1; }
  maintainers="$maintainers$user_keys
"
done
recipients=$(printf '%s' "$maintainers"; grep -v '^#' "$CI_RECIPIENT_FILE")

{
  echo "# Generated by scripts/sync-sops-recipients.sh from GitHub keys of: $GITHUB_USERS"
  echo "creation_rules:"
  echo "  - path_regex: ^$(echo "$SECRET" | sed 's/\./\\./g')\$"
  echo "    age: >-"
  echo "$recipients" | sed 's/^/      /; $!s/$/,/'
} > "$ROOT/.sops.yaml"

if [ -f "$ROOT/$SECRET" ]; then
  # Decrypts with ~/.ssh/id_ed25519 or SOPS_AGE_SSH_PRIVATE_KEY_FILE, and
  # shows the recipient change before asking to re-encrypt.
  (cd "$ROOT" && "$SOPS" updatekeys "$SECRET")
fi
echo "$(echo "$recipients" | wc -l) recipients written to .sops.yaml"
